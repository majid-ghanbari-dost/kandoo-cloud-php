<?php

declare(strict_types=1);

/**
 * Synthetic seed for the local customer-API read load test (PHP-B / P-34).
 *
 * Writes a temporary config with customer authentication ENABLED for the local read-only
 * benchmark, seeds ONE synthetic store + invoice + customer session, and prints one JSON
 * line the Python driver reads. Refuses anything but an isolated local demo/TEST database,
 * so it can never touch owner or production data.
 *
 *   php tools/dev/load-customer-seed.php /tmp/load-config.php
 *
 * Every value here is FAKE (TEST-… / placeholder phone and UUIDs). No SMS is sent.
 */

use Kandoo\Cloud\Config;
use Kandoo\Cloud\Customer\OtpSecrets;
use Kandoo\Cloud\Database;
use Kandoo\Cloud\Store\MariaDbGateway;

if (PHP_SAPI !== 'cli' || count($argv) !== 2) { exit(2); }
require dirname(__DIR__, 2).'/src/bootstrap.php';

try {
    $config = Config::load()->all();
    $name = $config['db']['name'];
    if (!in_array($config['db']['host'], ['127.0.0.1', 'localhost'], true)
        || !(($config['env'] === 'testing' && str_starts_with($name, 'TEST_'))
            || ($config['env'] === 'demo' && preg_match('/^kandoo_demo_[0-9a-f]{12}$/D', $name) === 1))) {
        throw new RuntimeException('Not an isolated local demo/test database');
    }
    // Synthetic-only policy values; the read throttle is DISABLED here so the benchmark
    // measures latency, while enforcement itself is proven in CustomerReadLimitDatabaseTest.
    $config['customer_auth'] = [
        'enabled' => true, 'code_length' => 6, 'code_ttl_seconds' => 300, 'max_attempts' => 3,
        'codes_per_announcement' => 2, 'issue_window_seconds' => 900, 'max_issues_per_window' => 3,
        'session_ttl_seconds' => 3600, 'device_numbers_per_day' => 3, 'device_ttl_seconds' => 2592000,
        'issue_ip_limit_per_minute' => 10, 'verify_ip_limit_per_minute' => 20,
        'read_ip_limit_per_minute' => 0, 'read_session_limit_per_minute' => 0,
        'otp_pepper' => 'TEST-only-synthetic-load-pepper-0123456789',
        'telegram_url' => null,
    ];
    $store = '11111111-1111-4111-8111-111111111111';
    $invoice = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
    $phone = '+989120000001';
    $token = OtpSecrets::sessionToken();

    $db = new Database($config);
    $gateway = new MariaDbGateway($db);
    $gateway->seedStore(['store_id' => $store, 'active_writer_device_id' => $store, 'active_writer_epoch' => 1,
        'accepted_through_seq' => 0, 'entry_count' => 0, 'head_entry_hash' => null, 'projection_version' => 0]);
    $gateway->seedProjection([
        'public_token' => 'TESTLOADCUSTOMERTOKEN1234567',
        'public_token_hash' => hash('sha256', 'TESTLOADCUSTOMERTOKEN1234567'),
        'digital_invoice_id' => $invoice, 'invoice_id' => $invoice, 'store_id' => $store,
        'store_name' => 'TEST Load Store', 'display_number' => 3, 'lifecycle_status' => 'ISSUED',
        'issued_at' => '2026-01-02 03:04:05', 'issued_payload' => '{}',
        'issued_content_sha256' => str_repeat('d', 64), 'payable_rials' => 99000,
        'line_items' => '[]', 'customer_phone' => $phone,
    ]);
    $pdo = $db->pdo();
    $pdo->exec('DELETE FROM customer_read_rate_buckets');
    $insert = $pdo->prepare('INSERT INTO cloud_customer_sessions (token_hash,phone,expires_at) VALUES (?,?,?) ON DUPLICATE KEY UPDATE phone=VALUES(phone), expires_at=VALUES(expires_at)');
    $insert->execute([OtpSecrets::sessionHash($token), $phone, time() + 1800]);

    $code = "<?php\n// GENERATED by tools/dev/load-customer-seed.php — FAKE synthetic load config, never committed.\nreturn ".var_export($config, true).";\n";
    if (file_put_contents($argv[1], $code, LOCK_EX) === false) { throw new RuntimeException('Cannot write temporary config'); }
    @chmod($argv[1], 0600);
    echo json_encode(['config' => $argv[1], 'token' => $token, 'store' => $store, 'invoice' => $invoice],
        JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR), PHP_EOL;
    exit(0);
} catch (Throwable $e) {
    fwrite(STDERR, 'Customer load seed refused: isolated local demo/TEST database required.'.PHP_EOL);
    exit(1);
}
