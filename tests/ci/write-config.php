<?php

declare(strict_types=1);

/**
 * CI helper — writes <app root>/config.php from environment variables at RUNTIME.
 * All values are FAKE CI-only credentials generated fresh per workflow run; nothing
 * secret is ever committed (no credentials in any repo, ever — PM ORDER 9).
 *
 * Local runs: copy config.example.php to config.php instead (or set KANDOO_CONFIG).
 */

$root = dirname(__DIR__, 2);

$bool = static function (string $name, bool $default): bool {
    $raw = getenv($name);
    if ($raw === false || $raw === '') {
        return $default;
    }
    return in_array(strtolower($raw), ['1', 'true', 'yes', 'on'], true);
};
$int = static function (string $name, int $default): int {
    $raw = getenv($name);
    return $raw === false || $raw === '' ? $default : (int) $raw;
};
$str = static function (string $name, string $default): string {
    $raw = getenv($name);
    return $raw === false || $raw === '' ? $default : $raw;
};

$config = [
    'base_url' => $str('KANDOO_BASE_URL', 'https://invoice.TEST-ci.invalid'),
    'db' => [
        'host'    => $str('KANDOO_DB_HOST', '127.0.0.1'),
        'port'    => $int('KANDOO_DB_PORT', 3306),
        'name'    => $str('KANDOO_DB_NAME', 'TEST_kandoo_cloud'),
        'user'    => $str('KANDOO_DB_USER', 'TEST_kandoo_user'),
        'pass'    => $str('KANDOO_DB_PASS', 'TEST-DB-PASSWORD'),
        'charset' => 'utf8mb4',
    ],
    'replication_key' => null,
    'public_rate_limit_per_minute' => $int('KANDOO_PUBLIC_RATE_LIMIT', 60),
    'ingest_rate_limit_per_minute' => $int('KANDOO_INGEST_RATE_LIMIT', 120),
    'public_legal_copy_required' => $bool('KANDOO_LEGAL_COPY_REQUIRED', false),
    'env' => 'testing',
];

$path = $root . '/config.php';
$code = "<?php\n"
    . "// GENERATED by tests/ci/write-config.php — FAKE CI-only values, never committed.\n"
    . 'return ' . var_export($config, true) . ";\n";

if (file_put_contents($path, $code) === false) {
    fwrite(STDERR, "Cannot write $path\n");
    exit(1);
}
echo "config.php written (FAKE CI values).", PHP_EOL;
